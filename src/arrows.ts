/**
 * **矢印を出すか**（`arrows`）。既定は出す。
 *
 * ## なぜ要るか
 *
 * 路線図を描こうとして分かった。**線に向きが無い図がある。**
 *
 * | 図 | 線の意味 | 向き |
 * |---|---|---|
 * | 構成図・業務フロー | 流れ・依存 | **ある** |
 * | 売場の補充動線・避難経路 | 人や物の動き | **ある** |
 * | 路線図 | **繋がっていること** | 無い |
 * | 配管の系統（往き還り） | 流れ | ある |
 * | 電気の単線結線 | **繋がっていること** | 無い（本来） |
 *
 * 路線図に矢印を付けると「西ヶ丘から桜台へ行く線」という**片道の意味**が出る。
 * 実際は両方向に走っていて、図が言いたいのは「繋がっている」だけ。
 *
 * ## 向きが無い線は、図の下に敷く
 *
 * 向きのある矢印は**図の上に載せる注記**（動線・避難経路）。
 * 向きの無い線は**図そのもの**で、駅や機器がその上に乗る。
 *
 * 路線図で線を駅の上に描くと、駅の印を線が串刺しにして潰す。
 */

export function arrowsOf(raw: unknown): boolean {
  return raw !== false;
}
