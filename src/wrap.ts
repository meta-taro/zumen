/**
 * **長い鎖を折り返すか**（`wrap`）。既定は折り返さない。
 *
 * ## なぜ要るか
 *
 * 折り返さないと、7 工程の業務フローが **横 2584 × 縦 124（比 20.8）** で出る。
 * 資料に貼ると幅に合わせて縮むので、**文字が読めない。**
 * 縦向き（`direction: down`）にしても、今度は 0.27:1 になるだけで解決しない。
 *
 * | ノード数 | 折り返し無し | 折り返し |
 * |---|---|---|
 * | 2 | 3.42 | **3.42（折り返さない）** |
 * | 3 | 5.16 | 2.18 |
 * | 4 | 6.90 | 2.18 |
 * | 5 | 8.65 | 3.14 |
 * | 8 | 13.87 | 2.17 |
 * | 12 | 20.84 | 2.83 |
 *
 * ## なぜ既定にしないか
 *
 * **折り返すと、辺が逆走して見える。**
 * 2 行目の先頭は 1 行目の末尾より左にあるので、繋ぐ辺が図を右から左へ戻る。
 *
 * これは [#1](https://github.com/meta-taro/zumen/issues/1) で報告された壊れ方
 * （**終点が最上段に来て、図の全高を逆流する矢印が生まれた**）と同じ絵になる。
 * 実際、既定にしたら `test/groups.test.ts` の 4 件が落ちた。
 *
 * **落ちたテストを消さずに、既定を変えないほうを採った。**
 * 折り返してよいかは図による —— 工程が 10 個ある業務フローなら折り返したいし、
 * 4 個の鎖なら一直線のほうが読める。**それを決めるのは人**（`DESIGN.md` の領分）。
 *
 * ## 書き方
 *
 * ```yaml
 * version: 1
 * wrap: true
 * ```
 */

/**
 * 折り返しの目標の比。**上限ではなく目標**で、ELK は近い値へ寄せるだけ。
 *
 * 2.8 を選んだのは、**2 個のときに折り返さない**いちばん小さい値だから。
 * 2.2 にすると「A → B」が縦に積まれる —— 2 つ並べるだけの図で折り返す理由は無い。
 * 4.0 まで上げると、今度は 3 個が 5.16 のまま折り返されなくなる。
 */
const TARGET_RATIO = '2.8';

export function wrapOf(raw: unknown): boolean {
  return raw === true;
}

/**
 * 折り返しの指定を ELK の言葉にする。折り返さないなら空。
 *
 * `SINGLE_EDGE` ではなく `MULTI_EDGE`。単辺だけを切ると、
 * **分岐のある図で切れる場所が見つからず、折り返しが効かない。**
 */
export function wrapOptions(wrap: boolean): Record<string, string> {
  if (!wrap) return {};
  return {
    'elk.layered.wrapping.strategy': 'MULTI_EDGE',
    'elk.aspectRatio': TARGET_RATIO,
  };
}
